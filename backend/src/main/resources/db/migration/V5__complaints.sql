-- A problem reported in a feedback form. Saved in the same transaction as its feedback.
-- reference_no has a random part, because it is the only key to the public status page.
CREATE TABLE complaints (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id   BIGINT                   NOT NULL REFERENCES feedback (id),
    camp_id       BIGINT                   NOT NULL REFERENCES camps (id),
    category_id   BIGINT                   NOT NULL REFERENCES complaint_categories (id),
    description   VARCHAR(1000)            NOT NULL,
    reference_no  VARCHAR(20)              NOT NULL,
    priority      VARCHAR(10)              NOT NULL DEFAULT 'MEDIUM',
    status        VARCHAR(20)              NOT NULL DEFAULT 'OPEN',
    assignee_id   BIGINT REFERENCES users (id),
    due_date      DATE,
    public_note   VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_complaints_feedback UNIQUE (feedback_id),
    CONSTRAINT uk_complaints_reference UNIQUE (reference_no),
    CONSTRAINT ck_complaints_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT ck_complaints_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED'))
);

CREATE INDEX idx_complaints_camp_status ON complaints (camp_id, status);
CREATE INDEX idx_complaints_assignee ON complaints (assignee_id);
