CREATE TABLE camps (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(150)             NOT NULL,
    location           VARCHAR(200)             NOT NULL,
    start_date         DATE                     NOT NULL,
    end_date           DATE                     NOT NULL,
    organizer_id       BIGINT                   NOT NULL REFERENCES users (id),
    status             VARCHAR(20)              NOT NULL,
    feedback_opens_on  DATE                     NOT NULL,
    feedback_closes_on DATE                     NOT NULL,
    public_token       VARCHAR(16)              NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_camps_public_token UNIQUE (public_token),
    CONSTRAINT ck_camps_status CHECK (status IN ('UPCOMING', 'ACTIVE', 'CLOSED', 'ARCHIVED')),
    CONSTRAINT ck_camps_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_camps_feedback_window CHECK (feedback_closes_on >= feedback_opens_on)
);

CREATE INDEX idx_camps_organizer ON camps (organizer_id);
CREATE INDEX idx_camps_start_date ON camps (start_date);

-- A service offered at a camp, such as "Cataract screening" under Eye Care.
-- Names are unique per camp (ignoring case); the service layer checks that, because a database
-- constraint would fail when a save removes one service and adds another with the same name.
CREATE TABLE camp_services (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_id       BIGINT       NOT NULL REFERENCES camps (id) ON DELETE CASCADE,
    department_id BIGINT       NOT NULL REFERENCES departments (id),
    name          VARCHAR(100) NOT NULL,
    sort_order    INTEGER      NOT NULL
);

CREATE INDEX idx_camp_services_camp ON camp_services (camp_id);
CREATE INDEX idx_camp_services_department ON camp_services (department_id);
