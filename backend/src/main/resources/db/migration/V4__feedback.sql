-- One submitted form. Anonymous unless the attendee asked for follow-up and agreed to be
-- contacted; contact columns are filled only then. No clinical details are collected.
CREATE TABLE feedback (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_id             BIGINT                   NOT NULL REFERENCES camps (id),
    camp_service_id     BIGINT REFERENCES camp_services (id),
    comment             VARCHAR(1000),
    problem_reported    BOOLEAN                  NOT NULL DEFAULT FALSE,
    follow_up_consent   BOOLEAN                  NOT NULL DEFAULT FALSE,
    contact_name        VARCHAR(100),
    contact_phone       VARCHAR(20),
    contact_email       VARCHAR(255),
    assisted            BOOLEAN                  NOT NULL DEFAULT FALSE,
    assisted_by_id      BIGINT REFERENCES users (id),
    language            VARCHAR(5)               NOT NULL,
    submission_token    VARCHAR(120)             NOT NULL,
    submitted_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_feedback_submission_token UNIQUE (submission_token),
    CONSTRAINT ck_feedback_language CHECK (language IN ('en', 'hi')),
    CONSTRAINT ck_feedback_contact_needs_consent CHECK (
        follow_up_consent OR (contact_name IS NULL AND contact_phone IS NULL AND contact_email IS NULL)),
    CONSTRAINT ck_feedback_assisted_by CHECK (assisted OR assisted_by_id IS NULL)
);

CREATE INDEX idx_feedback_camp_submitted ON feedback (camp_id, submitted_at);
CREATE INDEX idx_feedback_service ON feedback (camp_service_id);

CREATE TABLE feedback_ratings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id BIGINT   NOT NULL REFERENCES feedback (id) ON DELETE CASCADE,
    category_id BIGINT   NOT NULL REFERENCES rating_categories (id),
    score       SMALLINT NOT NULL,
    CONSTRAINT uk_feedback_ratings UNIQUE (feedback_id, category_id),
    CONSTRAINT ck_feedback_ratings_score CHECK (score BETWEEN 1 AND 5)
);

CREATE INDEX idx_feedback_ratings_category ON feedback_ratings (category_id);
