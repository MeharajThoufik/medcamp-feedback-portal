-- What attendees rate. Seeded for now; feature 14 makes the list editable, which is why the
-- labels live here instead of in the app's translation files.
CREATE TABLE rating_categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL,
    label_en   VARCHAR(100) NOT NULL,
    label_hi   VARCHAR(100) NOT NULL,
    sort_order INTEGER      NOT NULL,
    required   BOOLEAN      NOT NULL DEFAULT FALSE,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_rating_categories_code UNIQUE (code)
);

